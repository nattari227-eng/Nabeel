export function getNaeemTafsirForSurah(
  surahNumber: number,
  ayahNumbers: number[],
  juzByAyah?: Map<number, number>
): NaeemTafsirItem[] {
  const exactMap = SURAH_AYAH_TAFSIR[surahNumber] ?? {};
  const siratMatches = SIRAT_UL_JINAN_DATA.filter((s) => s.surahNumber === surahNumber);
  const surahSummary = SURAH_SUMMARY_TAFSIR[surahNumber];

  return ayahNumbers.map((ayahNo) => {
    const exact = exactMap[ayahNo];
    if (exact) {
      return { ayah: ayahNo, text: exact };
    }

    if (ayahNo === 1 && siratMatches.length > 0) {
      return {
        ayah: ayahNo,
        text: siratMatches[0].urduTafsir,
      };
    }

    if (ayahNo === 1 && surahSummary) {
      return {
        ayah: ayahNo,
        text: surahSummary,
      };
    }

    const juzNo = juzByAyah?.get(ayahNo) ?? 1;
    const jildNo = getJildForPara(juzNo);
    return {
      ayah: ayahNo,
      text: `نور العرفان (حکیم الامت مفتی احمد یار خان نعیمی رحمۃ اللہ علیہ) و صراط الجنان: اس آیتِ مبارکہ کا مستند ترجمہ کنز الایمان اوپر درج ہے۔ مزید تفصیلی حاشیہ و تفسیر کے لیے صراط الجنان / نور العرفان جلد ${jildNo} (پارہ ${juzNo}) ملاحظہ فرمائیں۔`,
    };
  });
}
