import { SiratVolume } from '../types/quran';
import { ALL_SURAHS } from './quranMetadata';

function fullSurahSpan(surahNumber: number) {
  const surah = ALL_SURAHS[surahNumber - 1];
  return {
    surahNumber,
    startAyah: 1,
    endAyah: surah.versesCount,
    isPartial: false,
  };
}

function partialSurahSpan(surahNumber: number, startAyah: number, endAyah: number) {
  return {
    surahNumber,
    startAyah,
    endAyah,
    isPartial: true,
  };
}

